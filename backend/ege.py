def public_tasks() -> list[dict]:
    return [{"id": row[0], "topic": row[1], "prompt": row[2], "unit": row[3]} for row in TASKS]


def grade_answer(task_id: int, answer: str) -> dict | None:
    task = next((row for row in TASKS if row[0] == task_id), None)
    if task is None:
        return None
    value = answer.strip().replace(",", ".")
    if not re.fullmatch(r"[+-]?(?:\d{1,30}(?:\.\d{1,30})?|\.\d{1,30})", value, re.ASCII):
        raise ValueError("Введите число без единиц измерения. Дробную часть отделяйте точкой или запятой.")
    return {"id": task_id, "is_correct": Decimal(value) == Decimal(task[4]),
            "correct_answer": task[4], "unit": task[3], "explanation": task[5], "source": BASE + task[6]}
